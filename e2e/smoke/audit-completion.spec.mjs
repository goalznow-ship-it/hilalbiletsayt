import { randomUUID } from "node:crypto";
import { test, expect } from "@playwright/test";
import { client, seedWorld, uiLogin } from "./helpers.mjs";

test("administrator publishes a priced exam and opens its Baku session; a mobile visitor buys it", async ({ page, browser }, testInfo) => {
  const world = await seedWorld();
  const code = `AUD-${randomUUID().slice(0, 8)}`;
  await uiLogin(page, process.env.ADMIN_EMAIL, process.env.ADMIN_PASSWORD);
  await page.goto("/dashboard/exams");
  await page.getByRole("button", { name: "Yeni imtahan", exact: true }).click();
  await page.locator("#exam-price").fill("35.50");
  await page.locator("input[name=code]").fill(code);
  await page.locator("input[name=title]").fill(code);
  await page.locator("select[name=status]").selectOption("PUBLISHED");
  await page.locator("form button[type=submit]").click();
  const card = page.locator('[data-slot="card"]').filter({ has: page.getByRole("heading", { name: `${code} · ${code}` }) });
  await expect(card).toBeVisible();
  await card.getByRole("button", { name: "Sessiyalar", exact: true }).click();
  const starts = new Date(Date.now() + 2 * 864e5 + 4 * 36e5).toISOString().slice(0, 16);
  const ends = new Date(Date.now() + 2 * 864e5 + 6 * 36e5).toISOString().slice(0, 16);
  await page.getByLabel("Sessiya kodu").fill(`${code}-S`);
  await page.getByLabel("Başlama vaxtı").fill(starts);
  await page.getByLabel("Bitmə vaxtı").fill(ends);
  await page.getByLabel("İmtahan yeri", { exact: true }).fill("Bakı, zal 3");
  await page.getByLabel("Tutum").fill("3");
  await page.getByRole("button", { name: "Sessiya yarat", exact: true }).click();
  await page.getByRole("button", { name: "Satışı aç", exact: true }).click();
  await expect(page.getByRole("button", { name: "Satışı bağla", exact: true })).toBeVisible();
  const catalog = await client().call("GET", "/public/exams");
  const exam = catalog.exams.find(row => row.code === code);
  expect(exam.price).toBe(3550);
  expect(exam.sessions[0].startsAt).toBe(new Date(`${starts}+04:00`).toISOString());

  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, timezoneId: "America/New_York", baseURL: process.env.BASE_URL });
  try {
    const phone = await context.newPage();
    await phone.goto("/");
    await phone.locator(".public-exam").filter({ hasText: code }).getByRole("button", { name: "Bilet al" }).click();
    await phone.getByLabel("Namizədin adı və soyadı").fill("Mobil Audit Namizədi");
    await phone.getByLabel("Valideynin mobil nömrəsi").fill("0501234567");
    await phone.getByLabel("Ödəniş ediləcək filial").selectOption(world.branch.id);
    await phone.locator(".public-order button[type=submit]").click();
    await expect(phone).toHaveURL(/\/orders\/[A-Za-z0-9_-]{43}$/);
    await expect(phone.getByText("Mobil Audit Namizədi", { exact: true })).toBeVisible();
    await expect(phone.getByText(/^PUB-[a-f0-9]{64}$/)).toBeVisible();
    expect(await phone.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
    await phone.screenshot({ path: testInfo.outputPath("mobile-receipt.png"), fullPage: true });
  } finally { await context.close(); }

  await page.goto("/dashboard/questions");
  await page.getByRole("combobox", { name: "İmtahan", exact: true }).selectOption(exam.id);
  await page.getByRole("button", { name: "Yeni sual" }).click();
  await page.getByLabel("Sual mətni").fill("2 + 2 neçədir?");
  await page.locator("#question-variants").fill("A) 3|B) 4|C) 5|D) 6");
  await page.getByLabel("Düzgün cavab nömrəsi").selectOption("2");
  await page.locator("#question-subject").fill("Riyaziyyat");
  await page.locator("#question-topic").fill("Toplama");
  await page.getByRole("button", { name: "Yarad", exact: true }).click();
  await expect(page.getByText("2 + 2 neçədir?", { exact: true })).toBeVisible();
  await expect(page.getByText("Riyaziyyat · Toplama", { exact: true })).toBeVisible();
  await page.goto("/dashboard/omr/keys");
  await page.getByRole("combobox", { name: "İmtahan", exact: true }).selectOption(exam.id);
  await page.getByLabel("Təsadüfi sual sayı").fill("1");
  await page.getByRole("button", { name: "Təsadüfi seç", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("1 sual təsadüfi seçildi");
  await page.getByRole("button", { name: "Açarı yarat", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Açar yaradıldı");
  const list = await client().call("GET", `/ticket?examId=${exam.id}`, { token: world.admin });
  const ticket = list.data[0];
  await page.goto("/dashboard/tickets");
  const ticketCard = page.locator('[data-slot="card"]').filter({ hasText: ticket.code });
  page.once("dialog", dialog => dialog.accept());
  await ticketCard.getByRole("button", { name: "Ödənişi təsdiqlə", exact: true }).click();
  await expect(ticketCard.getByText(/Ödənilib/)).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await ticketCard.getByRole("button", { name: "Ödənişi qaytar", exact: true }).click();
  await expect(ticketCard.getByText(/Geri qaytarılıb/)).toBeVisible();
  await page.goto("/dashboard/reports");
  await expect(page.getByRole("row").filter({ hasText: world.branch.name })).toContainText("Geri qaytarılıb");
  const downloaded = page.waitForEvent("download", { timeout: 15_000 });
  await page.getByRole("button", { name: "Excel ixrac et" }).click();
  expect((await downloaded).suggestedFilename()).toBe("hilal-sales.xlsx");
  await page.goto("/dashboard/settings");
  await expect(page.getByRole("status")).toContainText("Verilənlər bazası ilə əlaqə var");
  await page.getByRole("button", { name: "Yenidən yoxla" }).click();
  await expect(page.getByRole("status")).toContainText("Verilənlər bazası ilə əlaqə var");
  await page.goto("/dashboard");
  await expect(page.locator(".metric").filter({ hasText: "İşçilər və satıcılar" }).locator(".metric-value")).toHaveText(/^\d+$/);
});

test("administrator creates, edits and deactivates an employee through the dashboard", async ({ page }) => {
  const world = await seedWorld();
  const email = `browser-${randomUUID()}@audit.invalid`;
  await uiLogin(page, process.env.ADMIN_EMAIL, process.env.ADMIN_PASSWORD);
  await page.goto("/dashboard/users");
  await page.getByRole("button", { name: "Yeni istifadəçi", exact: true }).click();
  await page.getByLabel("E-poçt", { exact: true }).fill(email);
  await page.getByLabel("Tam ad", { exact: true }).fill("Browser Employee");
  await page.getByLabel("Şifrə (ən azı 12 simvol)", { exact: true }).fill("Browser-employee-password-123");
  await page.getByLabel("Rol", { exact: true }).selectOption("SELLER");
  await page.getByLabel("Filiallar", { exact: true }).selectOption([world.branch.id]);
  await page.getByRole("button", { name: "Yadda saxla", exact: true }).click();
  const employee = page.locator('[data-slot="card"]').filter({ hasText: email });
  await expect(employee).toBeVisible();
  await employee.getByRole("button", { name: "Redaktə et", exact: true }).click();
  await expect(page.locator('form button[type="submit"]')).toBeEnabled();
  await page.getByLabel("Tam ad", { exact: true }).fill("Updated Browser Employee");
  await page.getByLabel("Rol", { exact: true }).selectOption("BRANCH_MANAGER");
  await page.getByLabel("İstifadəçi aktivdir", { exact: true }).uncheck();
  await page.locator('form button[type="submit"]').click();
  await expect(employee).toContainText("Updated Browser Employee");
  await expect(employee).toContainText("BRANCH_MANAGER");
  const saved = await client().call("GET", `/users?search=${encodeURIComponent(email)}`, { token: world.admin });
  expect(saved.data[0].isActive).toBe(false);
});
